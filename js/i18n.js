    detectLanguage() {
        try {
            const saved = localStorage.getItem('tt_language');
            if (saved && this.supportedLanguages.includes(saved)) {
                return saved;
            }
        } catch (e) {}

        const browserLang = (navigator.language || navigator.userLanguage || 'tr').toLowerCase();
        const primaryCode = browserLang.split('-')[0];

        if (this.supportedLanguages.includes(primaryCode)) {
            return primaryCode;
        }

        return this.defaultLanguage;
    }

    setLanguage(lang) {
        if (!this.supportedLanguages.includes(lang)) return;
        this.currentLanguage = lang;
        try {
            localStorage.setItem('tt_language', lang);
        } catch (e) {}

        this.updateDOM();

        window.dispatchEvent(new CustomEvent('languagechange', {
            detail: { lang: this.currentLanguage }
        }));
    }

    t(key, params = {}) {
        const langData = this.translations[this.currentLanguage] || this.translations[this.defaultLanguage];
        let text = langData[key] || (this.translations['en'] && this.translations['en'][key]) || key;


        for (const [pKey, pVal] of Object.entries(params)) {
            text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal);
        }

        return text;
    }

    getCountryName(code) {
        const key = `country_${code}`;
        return this.t(key);
    }


    getArchetypeName(archKey) {
        const key = `arch_${archKey}`;
        return this.t(key);
    }

    getCountryStyle(code) {
        const key = `style_${code}`;
        return this.t(key);
    }

    init() {
        this.updateDOM();
    }

    updateDOM() {
        document.documentElement.lang = this.currentLanguage;
        document.title = "Table Tennis Reflex";

        const isTouch = ('ontouchstart' in window) || (navigator.maxTouchPoints > 0) || (window.innerWidth < 700);


        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (key) {
                if (isTouch && key === 'serve_instructions') {
                    el.textContent = this.t('serve_instructions_mobile');
                } else {
                    el.textContent = this.t(key);
                }
            }
        });


        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            if (key) {
                if (isTouch && key === 'controls_hint') {
                    el.innerHTML = this.t('controls_hint_mobile');
                } else {
                    el.innerHTML = this.t(key);
                }
            }
        });


        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (key) {
                el.setAttribute('title', this.t(key));
            }
        });


        document.querySelectorAll('.lang-select-input').forEach(sel => {
            sel.value = this.currentLanguage;
        });


        document.querySelectorAll('.lang-pill-btn').forEach(btn => {
            if (btn.getAttribute('data-lang') === this.currentLanguage) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    }
